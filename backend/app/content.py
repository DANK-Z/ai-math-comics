def get_comic(lang: Language) -> Comic:
    story = STORIES[lang]
    return Comic(
        lang=lang,
        title=story["title"],
        panels=[
            Panel(id=index, speaker=speaker, text=text, imageKey=f"pizza-{index:02d}")
            for index, (speaker, text) in enumerate(story["panels"], start=1)
        ],
        exercise=Exercise(prompt=PROMPTS[lang]),
    )
